package netzbegruenung.keycloak.authenticator.vonage;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import netzbegruenung.keycloak.authenticator.verification.SmsVerificationException;
import netzbegruenung.keycloak.authenticator.verification.SmsVerificationResult;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.keycloak.util.JsonSerialization;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Tests the requests VonageVerifyClient sends and how it reads the responses, against a
 * local stub that answers like the Verify v2 API specification says.
 */
class VonageVerifyClientTest {

	private static final String REQUEST_ID = "c11236f4-00bf-4b89-84ba-88b25df97315";

	private HttpServer server;
	private VonageVerifyClient client;

	private volatile int responseStatus;
	private volatile String responseBody;
	private volatile String requestMethod;
	private volatile String requestPath;
	private volatile String requestBody;
	private volatile String authorization;
	private volatile String contentType;

	@BeforeEach
	void startServer() throws IOException {
		server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
		server.createContext("/", this::handle);
		server.start();
		client = new VonageVerifyClient("http://127.0.0.1:" + server.getAddress().getPort() + "/", "key", "secret");
	}

	@AfterEach
	void stopServer() {
		server.stop(0);
	}

	private void handle(HttpExchange exchange) throws IOException {
		requestMethod = exchange.getRequestMethod();
		requestPath = exchange.getRequestURI().getPath();
		requestBody = new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8);
		authorization = exchange.getRequestHeaders().getFirst("Authorization");
		contentType = exchange.getRequestHeaders().getFirst("Content-Type");
		byte[] body = responseBody.getBytes(StandardCharsets.UTF_8);
		exchange.getResponseHeaders().add("Content-Type", "application/json");
		exchange.sendResponseHeaders(responseStatus, body.length == 0 ? -1 : body.length);
		if (body.length > 0) {
			exchange.getResponseBody().write(body);
		}
		exchange.close();
	}

	private void respond(int status, String body) {
		responseStatus = status;
		responseBody = body;
	}

	private static String error(String title, String detail) {
		return "{\"title\":\"" + title + "\",\"type\":\"https://developer.vonage.com/en/api-errors\",\"detail\":\"" + detail + "\",\"instance\":\"738f9313-418a-4259-9b0d-6670f06fa82d\"}";
	}

	@Test
	void startSendsSmsWorkflowAndReturnsRequestId() throws Exception {
		respond(202, "{\"request_id\":\"" + REQUEST_ID + "\"}");

		String requestId = client.start("491761234567", "ACME", 6, 300, "de-de", "4ed3027d-8762-44a0-aa3f-c393717413a4");

		assertEquals(REQUEST_ID, requestId);
		assertEquals("POST", requestMethod);
		assertEquals("/v2/verify", requestPath);
		assertEquals("application/json", contentType);
		assertEquals("Basic " + Base64.getEncoder().encodeToString("key:secret".getBytes(StandardCharsets.UTF_8)), authorization);
		Map<?, ?> body = JsonSerialization.readValue(requestBody, Map.class);
		assertEquals("ACME", body.get("brand"));
		assertEquals(6, body.get("code_length"));
		assertEquals(300, body.get("channel_timeout"));
		assertEquals("de-de", body.get("locale"));
		assertEquals("4ed3027d-8762-44a0-aa3f-c393717413a4", body.get("template_id"));
		assertEquals(List.of(Map.of("channel", "sms", "to", "491761234567")), body.get("workflow"));
		assertFalse(body.containsKey("code"), "The code is generated by Vonage");
	}

	@Test
	void startLeavesOutLocaleAndTemplateWhenNotSet() throws Exception {
		respond(202, "{\"request_id\":\"" + REQUEST_ID + "\"}");

		client.start("491761234567", "ACME", 4, 60, null, null);

		Map<?, ?> body = JsonSerialization.readValue(requestBody, Map.class);
		assertFalse(body.containsKey("locale"));
		assertFalse(body.containsKey("template_id"));
	}

	@Test
	void startFailsOnConcurrentVerification() {
		respond(409, error("Conflict", "Concurrent verifications to the same number are not allowed."));

		SmsVerificationException e = assertThrows(SmsVerificationException.class,
			() -> client.start("491761234567", "ACME", 6, 300, null, null));
		assertTrue(e.getMessage().contains("409"), e.getMessage());
		assertTrue(e.getMessage().contains("Concurrent verifications"), e.getMessage());
	}

	@Test
	void startFailsOnWrongCredentials() {
		respond(401, error("Unauthorized", "You did not provide correct credentials"));

		assertThrows(SmsVerificationException.class, () -> client.start("491761234567", "ACME", 6, 300, null, null));
	}

	@Test
	void startFailsWithoutRequestId() {
		respond(202, "{}");

		assertThrows(SmsVerificationException.class, () -> client.start("491761234567", "ACME", 6, 300, null, null));
	}

	@Test
	void startFailsWhenVonageIsNotReachable() {
		server.stop(0);

		assertThrows(SmsVerificationException.class, () -> client.start("491761234567", "ACME", 6, 300, null, null));
	}

	@Test
	void checkSendsCodeToTheRequest() throws Exception {
		respond(200, "{\"request_id\":\"" + REQUEST_ID + "\",\"status\":\"completed\"}");

		assertEquals(SmsVerificationResult.VALID, client.check(REQUEST_ID, "123456"));
		assertEquals("POST", requestMethod);
		assertEquals("/v2/verify/" + REQUEST_ID, requestPath);
		assertEquals(Map.of("code", "123456"), JsonSerialization.readValue(requestBody, Map.class));
	}

	@Test
	void checkMapsWrongCodeToInvalid() {
		respond(400, error("Invalid Code", "The code you provided does not match the expected value."));

		assertEquals(SmsVerificationResult.INVALID, client.check(REQUEST_ID, "000000"));
	}

	@Test
	void checkMapsTooManyAttemptsToExpired() {
		respond(410, error("Invalid Code", "An incorrect code has been provided too many times. Workflow terminated."));

		assertEquals(SmsVerificationResult.EXPIRED, client.check(REQUEST_ID, "000000"));
	}

	@Test
	void checkMapsUnknownRequestToExpired() {
		respond(404, error("Not Found", "The request ID provided could not be found."));

		assertEquals(SmsVerificationResult.EXPIRED, client.check(REQUEST_ID, "123456"));
	}

	@Test
	void checkMapsOtherFailuresToError() {
		respond(429, error("Rate Limit Hit", "Please wait, then retry your request"));
		assertEquals(SmsVerificationResult.ERROR, client.check(REQUEST_ID, "123456"));

		respond(500, "");
		assertEquals(SmsVerificationResult.ERROR, client.check(REQUEST_ID, "123456"));

		server.stop(0);
		assertEquals(SmsVerificationResult.ERROR, client.check(REQUEST_ID, "123456"));
	}

	@Test
	void phoneNumberIsSentWithoutPlusOrInternationalPrefix() throws Exception {
		assertEquals("491761234567", VonageVerifyProvider.toVonageNumber("+49 176 1234567", ""));
		assertEquals("491761234567", VonageVerifyProvider.toVonageNumber("0049 176 1234567", ""));
		assertEquals("491761234567", VonageVerifyProvider.toVonageNumber("0176 1234567", "+49"));
		assertThrows(SmsVerificationException.class, () -> VonageVerifyProvider.toVonageNumber(null, "+49"));
	}
}
